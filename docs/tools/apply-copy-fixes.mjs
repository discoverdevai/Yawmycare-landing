function flat(o, p = "", out = {}) {
  if (o && typeof o === "object") for (const k of Object.keys(o)) flat(o[k], p ? `${p}.${k}` : k, out);
  else out[p] = o;
  return out;
}
function setPath(o, p, v) {
  const ks = p.split(".");
  let c = o;
  for (const k of ks.slice(0, -1)) {
    if (c[k] === undefined) throw new Error("missing path " + p);
    c = c[k];
  }
  const last = ks.at(-1);
  if (c[last] === undefined) throw new Error("missing leaf " + p);
  c[last] = v;
}

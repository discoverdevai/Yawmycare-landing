// Generates docs/arabic-review.md from the i18n JSON.
// Usage: node docs/tools/gen-arabic-review.mjs
// Status: "verbatim (owner Figma)" for strings taken word for word from the old AR Figma frame,
// everything else "draft, needs native review". The verbatim list below comes from the former
// per-section arabic-review.md files; edit it when the owner supplies/approves more text.
import fs from "node:fs";
import path from "node:path";

const docs = path.resolve(import.meta.dirname, "..");
const root = path.resolve(docs, "../src/i18n");

// file label -> keys (flat dotted/indexed paths) that are the owner's own Arabic.
const VERBATIM = {
  common: ["cta.bookDemo"],
  header: ["nav.items[0].label", "nav.items[2].label"],
  footer: ["cta.title", "links.home", "links.why"],
  setup: [
    "steps[0].title", "steps[0].body", "steps[1].title", "steps[1].body",
    "steps[2].title", "steps[2].body", "steps[3].title", "steps[3].body", "band.lead",
  ],
  security: ["title", "lead", "items[2].title"],
  demo: [
    "title", "fields.name.label", "fields.nursery.label", "fields.email.label", "fields.date.label",
    "fields.time.label", "fields.name.placeholder", "fields.nursery.placeholder",
    "fields.email.placeholder", "submit",
  ],
};
// Verbatim strings that were later corrected for a clear grammar error (see FIX-LOG-copy.md).
const GRAMMAR_FIXED = { demo: ["lead"] };

function flat(o, p = "", out = []) {
  if (Array.isArray(o)) o.forEach((v, i) => flat(v, `${p}[${i}]`, out));
  else if (o && typeof o === "object") for (const k of Object.keys(o)) flat(o[k], p ? `${p}.${k}` : k, out);
  else out.push([p, o]);
  return out;
}

const pairs = [["common", "en.json", "ar.json"]];
for (const f of fs.readdirSync(path.join(root, "sections")).sort()) {
  if (f.endsWith(".en.json")) {
    const slug = f.replace(".en.json", "");
    pairs.push([slug, `sections/${f}`, `sections/${slug}.ar.json`]);
  }
}

const esc = (s) => String(s).replace(/\|/g, "\\|").replace(/ /g, " ").replace(/\n/g, " ");
const rows = [];
let verbatim = 0, draft = 0;
for (const [label, e, a] of pairs) {
  const en = Object.fromEntries(flat(JSON.parse(fs.readFileSync(path.join(root, e), "utf8"))));
  const ar = flat(JSON.parse(fs.readFileSync(path.join(root, a), "utf8")));
  for (const [key, val] of ar) {
    if (typeof val !== "string") continue;
    if (/(^|\.)id$/.test(key) || /\.id$/.test(key) || key === "wordmark") continue;
    let status = "draft, needs native review";
    if ((VERBATIM[label] || []).includes(key)) status = "verbatim (owner Figma)";
    if ((GRAMMAR_FIXED[label] || []).includes(key)) status = "owner Figma, grammar-fixed (confirm)";
    if (status.startsWith("verbatim")) verbatim++; else draft++;
    rows.push(`| ${label} | \`${key}\` | ${esc(en[key] ?? "")} | ${esc(val)} | ${status} |`);
  }
}

const out = `# Arabic copy: consolidated review table

Generated by \`docs/tools/gen-arabic-review.mjs\` from \`src/i18n/**\`. Do not edit by hand; re-run the script.
Source reviews: \`docs/reviews/arabic-copy.md\` (74 findings, applied in \`docs/FIX-LOG-copy.md\`).
Strings: ${rows.length} (${verbatim} verbatim from the owner's Figma frame, ${draft} drafted and needing a native review).
Open owner questions: \`docs/OWNER-CLAIMS.md\` and \`docs/FIX-LOG-copy.md\`.

| file | key | EN | AR | status |
|---|---|---|---|---|
${rows.join("\n")}
`;
fs.writeFileSync(path.join(docs, "arabic-review.md"), out);
console.log(`wrote docs/arabic-review.md: ${rows.length} rows (${verbatim} verbatim, ${draft} draft)`);
